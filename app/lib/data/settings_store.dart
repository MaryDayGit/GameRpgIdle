import 'dart:convert';
import 'dart:io';
import 'dart:math';
import 'dart:ui' as ui;

import 'package:rift/core/model/lang.dart';

/// Настройки приложения: язык, звук, вибрация, пройдено ли обучение.
///
/// Отдельный файл, а не поле в сейве, потому что это не состояние игры.
/// Сейв описывает Заставу и наёмников — он переживает переустановку, его
/// мигрируют версиями. Выключенный звук такой судьбы не заслуживает, и
/// хранить его вместе с профилем значило бы гонять миграцию из-за галочки.
class AppSettings {
  AppSettings({
    this.lang = Lang.ru,
    this.sound = true,
    this.haptics = true,
    this.tutorialDone = false,
    this.analytics = true,
    String? deviceId,
    Set<String>? tutorialSeen,
  })  : deviceId = deviceId ?? newDeviceId(),
        tutorialSeen = tutorialSeen ?? <String>{};

  /// Язык игры.
  ///
  /// Здесь, а не в сейве, по той же причине, что и звук: это настройка
  /// устройства, а не состояние игры. Но следствие важнее — язык читается
  /// ДО контента (`GameController.boot`), потому что от него зависит, какие
  /// накладки грузить, а сейв к этому моменту ещё не открыт.
  Lang lang;

  bool sound;
  bool haptics;

  /// Обучение пройдено или пропущено. Показывать его второй раз — худшее,
  /// что можно сделать с игроком, который уже разобрался.
  ///
  /// Раньше поле поднималось сразу после вступительного окна, и означало
  /// «вступление прочитано». Теперь оно означает то, что написано: сценарий
  /// первого запуска пройден целиком или пропущен кнопкой. Старые сейвы от
  /// этого не страдают — у них поле уже `true`, и обучение к ним не лезет.
  bool tutorialDone;

  /// Отправлять ли обезличенную статистику игры.
  ///
  /// По умолчанию включено, и выключатель стоит в настройках рядом со звуком
  /// — не спрятан за отдельным экраном согласия. Собирается только состояние
  /// ИГРЫ (`lib/core/telemetry/game_events.dart`): глубина, сборка, что
  /// убило. Ничего, что указывает на человека, поэтому спрашивать разрешения
  /// до первого кадра не нужно, а дать возможность отказаться — нужно.
  ///
  /// Здесь, а не в сейве, по той же причине, что звук и язык: это настройка
  /// устройства. Следствие тоже то же — читается ДО контента, потому что
  /// аналитика поднимается в `GameController.boot()` вместе со всем
  /// остальным, и решать «слать или нет» после первого события поздно.
  bool analytics;

  /// Кто этот телефон — с точки зрения сейва.
  ///
  /// Не сведения об устройстве: это случайное число, заведённое при первом
  /// запуске, и оно не говорит ни про модель, ни про человека. Игра не
  /// собирает ни того, ни другого (`docs/11-ANALYTICS.md` §5), а IMEI и
  /// Android ID — это ещё и разрешения, и строка в Play Data Safety.
  ///
  /// Нужно ровно для одного: отличить «этот сейв в облако выгружали мы» от
  /// «его выгружал планшет» (`rift/core/save/save_sync.dart`). Для этого
  /// достаточно, чтобы идентификаторы РАЗЛИЧАЛИСЬ, — а откуда они взялись,
  /// решению безразлично.
  ///
  /// Здесь, в настройках, а не в сейве: сейв уезжает в облако и приезжает на
  /// другой телефон, и приехавший вместе с ним идентификатор объявил бы
  /// планшет телефоном.
  final String deviceId;

  /// Новый идентификатор устройства: 16 шестнадцатеричных знаков.
  static String newDeviceId() {
    final rng = Random.secure();
    final buffer = StringBuffer();
    for (var i = 0; i < 8; i++) {
      buffer.write(rng.nextInt(256).toRadixString(16).padLeft(2, '0'));
    }
    return buffer.toString();
  }

  /// Шаги обучения, которые игрок уже прошёл — или которые опоздали.
  ///
  /// Множество, а не номер шага: сценарий не линеен. Игрок, разобравший
  /// добычу раньше, чем ему про неё сказали, не должен упереться в подсказку,
  /// которой нечего показать, — а с номером шага упёрся бы.
  final Set<String> tutorialSeen;

  Map<String, dynamic> toJson() => {
        'lang': lang.code,
        'sound': sound,
        'haptics': haptics,
        'tutorialDone': tutorialDone,
        'analytics': analytics,
        'deviceId': deviceId,
        'tutorialSeen': tutorialSeen.toList(),
      };

  /// Читает настройки, прощая всё. Испорченный файл настроек не повод не
  /// пустить игрока в игру: непонятое поле берётся по умолчанию.
  factory AppSettings.fromJson(Map<String, dynamic> j) => AppSettings(
        // Неизвестный код языка — русский, а не отказ: файл настроек,
        // написанный будущей версией с ещё одним языком, обязан открыться.
        lang: Lang.byCode(j['lang'] is String ? j['lang'] as String : null),
        sound: j['sound'] is bool ? j['sound'] as bool : true,
        haptics: j['haptics'] is bool ? j['haptics'] as bool : true,
        tutorialDone:
            j['tutorialDone'] is bool ? j['tutorialDone'] as bool : false,
        // Отсутствие поля — согласие: файл настроек, написанный версией до
        // аналитики, принадлежит игроку, который об отказе не просил.
        // Обратное правило («нет поля — не слать») означало бы, что после
        // обновления молчат все, кто уже играл, и первый же отчёт описывал
        // бы только новичков.
        analytics: j['analytics'] is bool ? j['analytics'] as bool : true,
        // Файл без идентификатора — это первый запуск или файл до облака.
        // И то и другое честно получает новый: считать «неизвестное
        // устройство» одним и тем же устройством значит склеить два телефона
        // в один и потерять единственный признак, по которому они
        // различаются.
        deviceId: j['deviceId'] is String && (j['deviceId'] as String).isNotEmpty
            ? j['deviceId'] as String
            : null,
        // Незнакомый шаг не выбрасывается: файл, написанный будущей версией
        // с другим сценарием, обязан открыться, а лишний идентификатор в
        // множестве не стоит ничего.
        tutorialSeen: {
          for (final id in (j['tutorialSeen'] is List
              ? j['tutorialSeen'] as List
              : const []))
            if (id is String) id,
        },
      );
}

/// Язык, на котором телефон говорит со своим хозяином.
///
/// Спрашивается у `PlatformDispatcher`, а не у `Platform.localeName`: на
/// Android 13+ у приложения есть СВОЙ язык, выставленный в настройках
/// системы отдельно от общего, и знает о нём только движок Flutter.
///
/// Берётся весь список предпочтений, а не первая строка: телефон, у которого
/// первым стоит язык, которого в игре нет, обычно вторым называет тот,
/// который есть, — и это ровно тот случай, ради которого человек список и
/// заполнял.
///
/// **Не совпал никто — английский, а не русский.** Русский здесь выглядит
/// естественным умолчанием (игра писалась на нём, и он единственный заполнен
/// целиком), но умолчание выбирается не для автора, а для того, кто открыл
/// игру. Телефон, настроенный на португальский, принадлежит человеку,
/// который русского скорее не знает; английский он прочтёт с большей
/// вероятностью, чем любой другой второй язык. Русский остаётся ответом
/// только для того, кто назвал русский.
Lang deviceLang() {
  try {
    for (final locale in ui.PlatformDispatcher.instance.locales) {
      final lang = Lang.byTag(locale.languageCode);
      if (lang != null) return lang;
    }
  } on Object {
    // Движок не ответил — не повод не запускаться.
  }
  return Lang.en;
}

/// Файл настроек рядом с сейвом.
class SettingsStore {
  SettingsStore(
    this.directory, {
    this.fileName = 'rift.settings.json',
    Lang? device,
  }) : _device = device;

  final Directory directory;
  final String fileName;

  /// Язык телефона — тот, на котором заговорит игра, у которой ещё не
  /// спрашивали. Параметром, а не обращением к системе прямо в [load]:
  /// иначе первый запуск нельзя проверить тестом, не подменив весь движок.
  ///
  /// Спрашивается лениво: хранилище заводят и там, где язык не понадобится
  /// вовсе (запись настроек), а `PlatformDispatcher` в такой момент может
  /// быть ещё и не поднят.
  final Lang? _device;

  File get _file => File('${directory.path}/$fileName');

  /// Читает настройки; если файла нет — заводит их по телефону.
  ///
  /// Первый запуск — это ровно «файла нет». Игра, начавшая обучение
  /// по-русски у человека с английским телефоном, теряет его на первом же
  /// экране: он не выбирал русский, ему его выдали.
  ///
  /// А вот файл, который ЕСТЬ, языку телефона не подчиняется ни в каком
  /// виде, даже испорченный: он означает, что игру уже открывали. Сюда же
  /// относится файл без записи о языке — он написан версией до перевода, и
  /// принадлежит тому, кто всё это время играл по-русски (`AppSettings.
  /// fromJson`). Переключить его по локали значило бы отобрать язык у того,
  /// кто в нём уже освоился.
  AppSettings load() {
    try {
      if (!_file.existsSync()) return AppSettings(lang: _device ?? deviceLang());
      final raw = jsonDecode(_file.readAsStringSync());
      if (raw is! Map) return AppSettings();
      return AppSettings.fromJson(raw.cast<String, dynamic>());
    } on Object {
      // Настройки не стоят того, чтобы из-за них не запускалась игра.
      return AppSettings();
    }
  }

  void save(AppSettings settings) {
    try {
      _file.writeAsStringSync(jsonEncode(settings.toJson()));
    } on FileSystemException {
      // Не записались — переживём: в следующий раз спросим заново.
    }
  }
}
