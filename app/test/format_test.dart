import 'package:flutter_test/flutter_test.dart';
import 'package:rift_app/ui/format.dart';

/// Строки с числами встречаются на каждом экране, и «3 осколков» читается
/// как недоделка. Правило простое, но ошибиться в нём легко именно на
/// одиннадцати и на числах, кончающихся на единицу.
void main() {
  test('согласование числительного', () {
    expect(plural(1, 'осколок', 'осколка', 'осколков'), '1 осколок');
    expect(plural(2, 'осколок', 'осколка', 'осколков'), '2 осколка');
    expect(plural(4, 'осколок', 'осколка', 'осколков'), '4 осколка');
    expect(plural(5, 'осколок', 'осколка', 'осколков'), '5 осколков');
    expect(plural(0, 'осколок', 'осколка', 'осколков'), '0 осколков');
  });

  test('одиннадцать — не единица', () {
    // Ровно то место, где правило «по последней цифре» врёт.
    expect(plural(11, 'этаж', 'этажа', 'этажей'), '11 этажей');
    expect(plural(12, 'этаж', 'этажа', 'этажей'), '12 этажей');
    expect(plural(14, 'этаж', 'этажа', 'этажей'), '14 этажей');
    expect(plural(21, 'этаж', 'этажа', 'этажей'), '21 этаж');
    expect(plural(22, 'этаж', 'этажа', 'этажей'), '22 этажа');
    expect(plural(111, 'этаж', 'этажа', 'этажей'), '111 этажей');
    expect(plural(121, 'этаж', 'этажа', 'этажей'), '121 этаж');
  });
}
