/// Уникальный эффект реликта. Реликт меняет правило, а не цифру, поэтому
/// каждый эффект — отдельная ветка в рантайме, а не строка в таблице
/// (`docs/04-RELICS.md`).
enum RelicEffect {
  burnCanCrit,
  twoHandedInOneHand,
  singleActive,
  permanentLowLife,
  doubleCounters,
  recordRun,
  eternalCurse,
  passivesOnly,

  // --- Бой -------------------------------------------------------------------

  /// Каждый удар критический, но базовый урон срезан.
  alwaysCrit,

  /// Первый удар по волне усилен, остальные ослаблены.
  firstStrike,

  /// Враг ниже порога здоровья гибнет мгновенно, зато урон срезан.
  executeLow,

  /// Броня не работает вовсе, зато все сопротивления выше.
  armorIntoResist,

  /// Обе оси урона выше, но запас здоровья вдвое меньше.
  fragilePower,

  /// Каждый полученный удар копит урон до конца волны.
  painToPower,

  /// Лечит только вампиризм: ни отдых, ни регенерация не работают.
  bloodPact,

  // --- Способности -----------------------------------------------------------

  /// Способности не стоят маны, но перезаряжаются дольше.
  freeCasts,

  /// Перезарядки короче, мана дороже.
  swiftCasts,

  /// Весь урон героя становится одной стихией — и она же его слабость.
  elementalConduit,

  // --- Спуск -----------------------------------------------------------------

  /// Не отдыхает между этажами, зато этажи короче.
  restless,

  /// Боссы щедрее, обычные враги крепче.
  bossbane,

  /// Спуск начинается глубже, но запас здоровья меньше.
  deepStart,

  /// Кольца дают вдвое, амулет не работает.
  twinRings,
}
