import 'stat_key.dart';
import 'tags.dart';

/// Осколок аффикса.
///
/// Хранит ПЕРЦЕНТИЛЬ ролла, а не значение, и в этом весь смысл (GDD §5.3).
/// Предметы обесцениваются каждые двадцать этажей — если бы осколок нёс
/// абсолютное число, крафт устаревал бы вместе с ними, и вкладываться в него
/// было бы бессмысленно. Перцентиль же пересчитывается под уровень нового
/// предмета, поэтому осколок 96-го перцентиля остаётся ценным на любой
/// глубине и становится вещью, которую игрок несёт через все раны.
class Shard {
  const Shard({
    required this.affixId,
    required this.stat,
    required this.percentile,
    this.tag,
  });

  /// Какой именно аффикс. По нему берётся база и правило масштабирования.
  final String affixId;

  final StatKey stat;

  /// 0..1. Уже с вычетом платы за извлечение.
  final double percentile;

  /// Для семейства `tagDamage` — тег, по которому был ролл.
  final Tag? tag;

  /// Качество осколка сотнями — то, как игрок о нём думает и говорит.
  int get quality => (percentile * 100).round();

  @override
  String toString() =>
      'Shard($affixId${tag != null ? ':${tag!.name}' : ''} p$quality)';
}
