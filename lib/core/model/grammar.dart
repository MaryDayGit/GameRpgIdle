/// Род — чтобы игра говорила по-русски.
///
/// Живой прогон дал это замечанием «иногда странные слова», и слова были
/// такие: «Кольцо · Редкий», «Перчатки распылён», «Мирена Последний»,
/// «„Кровавая пиявка“ пал». Каждое из них — согласование, которого не было:
/// текст собирался из кусков, а род кусков никто не спрашивал.
///
/// Правило здесь одно: **если строка собирается из частей, род берётся у
/// той части, которая задаёт смысл**, а не подразумевается мужским.
enum Gender {
  masculine,
  feminine,
  neuter,

  /// Множественное число: «Перчатки», «Ботинки». Формально не род, но ведёт
  /// себя так же — согласуется отдельной формой.
  plural,
}

/// Четыре формы прилагательного. Порядок фиксирован и совпадает с [Gender].
///
/// Класс, а не карта: карта позволяет забыть форму, и забытая форма
/// проявится опечаткой на экране, а не ошибкой компиляции.
class Forms {
  const Forms(this.masculine, this.feminine, this.neuter, this.plural);

  final String masculine;
  final String feminine;
  final String neuter;
  final String plural;

  String of(Gender gender) => switch (gender) {
        Gender.masculine => masculine,
        Gender.feminine => feminine,
        Gender.neuter => neuter,
        Gender.plural => plural,
      };
}
