/// Язык, на котором игра говорит с игроком.
///
/// Живёт в ядре, а не в клиенте, потому что говорит с игроком именно ядро:
/// названия статов, тегов, слотов, построек и рангов лежат здесь, и здесь же
/// собираются описания аффиксов. Клиент только показывает готовую строку.
///
/// Текущий язык — статик, а не параметр в каждом вызове. Причина та же, по
/// которой статиком сделаны [ContentPack] и `Tuning`: текст собирается в двух
/// десятках мест, и протаскивать локаль через каждую сигнатуру значило бы
/// переписать половину ядра ради значения, которое в пределах одного кадра
/// одинаково везде.
///
/// **ВАЖНО, та же оговорка, что у контента:** статики в Dart живут в пределах
/// изолята. Установка языка в `main()` НЕ настраивает фоновый изолят — там
/// останется умолчание, и симуляция вернёт русские строки в английскую игру.
/// Поэтому язык передаётся на вход изолята вместе с контентом.
library;

/// Поддерживаемые языки.
///
/// Список закрытый и лежит в коде, а не в контенте: добавление языка — это не
/// правка числа, а новый файл накладок, новая колонка в каждом [Phrase] и
/// решение о правилах согласования. Компилятор обязан потребовать их все.
enum Lang {
  ru('ru', 'Русский'),
  en('en', 'English');

  const Lang(this.code, this.title);

  /// Код по BCP 47. Он же имя каталога накладок контента
  /// (`assets/content/en/`) и значение, которое хранится в настройках.
  final String code;

  /// Название языка НА НЁМ САМОМ, и поэтому не переводится: в списке выбора
  /// игрок ищет знакомое слово. «Русский», подписанный как «Russian», не
  /// найдёт тот, кому он нужен.
  final String title;

  /// Язык по коду. Неизвестный код — не ошибка: сейв из будущей версии с
  /// языком, которого здесь ещё нет, должен открыться, а не отказать.
  static Lang byCode(String? code) =>
      values.where((l) => l.code == code).firstOrNull ?? ru;

  /// Текущий язык. Русский по умолчанию: игра писалась на нём, и он —
  /// единственный, у которого гарантированно заполнено всё.
  static Lang current = ru;
}

/// Строка, у которой есть форма на каждом языке.
///
/// Класс с полем на язык, а не `Map<Lang, String>`, по той же причине, по
/// которой классом сделан [Forms] в `grammar.dart`: карта позволяет забыть
/// язык, и забытый язык проявится пустотой на экране, а не ошибкой
/// компиляции. Добавление языка обязано ломать сборку, а не текст.
class Phrase {
  const Phrase(this._ru, this._en);

  /// Одно слово на всех языках: имя собственное, число, символ. Существует,
  /// чтобы такие места было видно как решение, а не как недоперевод.
  const Phrase.same(String both)
      : _ru = both,
        _en = both;

  final String _ru;
  final String _en;

  /// Форма на текущем языке.
  String get text => of(Lang.current);

  String of(Lang lang) => switch (lang) {
        Lang.ru => _ru,
        Lang.en => _en,
      };

  /// Чтобы `'$phrase'` в строковом шаблоне давал текст, а не `Instance of`.
  @override
  String toString() => text;
}
