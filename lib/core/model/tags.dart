import 'lang.dart';

/// Теги — клей всей системы (GDD §3.4).
///
/// Аффиксы ссылаются на теги, а не на конкретные способности. Новая
/// способность с тегом [fire] автоматически входит во все существующие
/// огненные билды: контент масштабируется мультипликативно, а не линейно.
///
/// ## Четыре оси, а не один список
///
/// Живой прогон дал приговор: «выбор без выбора, одна автоатака, очень мало
/// тегов у скилов». Разбор показал причину — тегов было восемь, они лежали
/// одной кучей, и у восьми способностей из тридцати одной тега не было вовсе.
/// Способность с одним тегом входит ровно в один билд; способность без тегов
/// не входит ни в один.
///
/// Поэтому теги разложены по осям, и у каждой способности есть тег с КАЖДОЙ
/// оси, которая к ней применима:
///
///  * **стихия** — чем бьёт. Она же тип урона, который режется сопротивлением;
///  * **форма** — [attack] или [spell]. Это не украшение: от формы зависит,
///    от какого стата способность растёт ([StatKey.attackDamage] или
///    [StatKey.spellPower]). Ось, ради которой снаряжение вообще может
///    подбираться под способности;
///  * **доставка** — [projectile], [area]: по скольким целям и как;
///  * **механика** — [duration], [curse], [aura], [totem], [strike], [blood].
///
/// Четыре оси означают, что одна способность лежит на пересечении трёх-четырёх
/// билдов, и «+25 % к урону Снарядами» усиливает её вместе с ещё пятью.
enum Tag {
  // --- Стихии ---------------------------------------------------------------
  fire(Phrase('Огонь', 'Fire'), Phrase('к урону Огнём', 'Fire damage')),
  cold(Phrase('Холод', 'Cold'), Phrase('к урону Холодом', 'Cold damage')),
  lightning(Phrase('Молния', 'Lightning'),
      Phrase('к урону Молнией', 'Lightning damage')),
  voidTag(Phrase('Пустота', 'Void'), Phrase('к урону Пустотой', 'Void damage')),
  physical(Phrase('Физический', 'Physical'),
      Phrase('к физическому урону', 'Physical damage')),

  // --- Форма ----------------------------------------------------------------
  /// Растёт от [StatKey.attackDamage] — от оружия.
  attack(Phrase('Атака', 'Attack'), Phrase('к урону Атаками', 'Attack damage')),

  /// Растёт от [StatKey.spellPower] — от посоха, фокуса и вложений в чары.
  ///
  /// Отдельная ось существует ровно ради одного: чтобы выбор способности
  /// менял то, какое снаряжение игроку нужно. Пока всё росло от урона оружия,
  /// любая вещь одинаково годилась любой сборке.
  spell(Phrase('Чары', 'Spell'), Phrase('к урону Чарами', 'Spell damage')),

  // --- Доставка -------------------------------------------------------------
  projectile(Phrase('Снаряд', 'Projectile'),
      Phrase('к урону Снарядами', 'Projectile damage')),
  area(Phrase('Область', 'Area'), Phrase('к урону по области', 'Area damage')),

  // --- Механика -------------------------------------------------------------
  duration(Phrase('Длительность', 'Duration'),
      Phrase('к длительному урону', 'damage over time')),
  strike(Phrase('Удар', 'Strike'), Phrase('к урону Ударами', 'Strike damage')),
  blood(Phrase('Кровь', 'Blood'), Phrase('к урону Кровью', 'Blood damage')),
  totem(Phrase('Тотем', 'Totem'), Phrase('к урону Тотемами', 'Totem damage')),
  /// Единственный тег, который усиливает НЕ урон.
  ///
  /// Ауры урона не наносят вовсе — они дают статы и замедляют. Аудит
  /// содержимого нашёл «Ауру» единственной дырой из пятнадцати тегов:
  /// множителя «+% к урону Аурами» некуда было применить, и ни один аффикс
  /// его не давал. Тег стоял в отборе способностей и не значил ничего.
  ///
  /// Теперь он множит ВЕЛИЧИНУ ауры: сколько брони даёт «Каменная стойка»,
  /// насколько замедляет «Морозный покров».
  aura(Phrase('Аура', 'Aura'), Phrase('к силе Аур', 'Aura effect')),
  curse(Phrase('Проклятие', 'Curse'),
      Phrase('к урону Проклятиями', 'Curse damage'));

  const Tag(this._title, this._damage);

  final Phrase _title;
  final Phrase _damage;

  /// Название тега — так он подписан на чипе способности.
  String get title => _title.text;

  /// Как тег читается в строке про урон: «+18 % к урону Огнём»,
  /// «+18% Fire damage».
  ///
  /// Отдельным полем, а не названием в шаблоне, потому что русский склоняется,
  /// а шаблон — нет. «+18 % к урону с тегом Огонь» — это запись разработчика;
  /// игрок видит в дереве пассивок «к урону Огнём» и должен видеть на вещи то
  /// же самое. Английскому падеж не нужен, но нужен порядок слов, и он тоже
  /// принадлежит тегу, а не шаблону.
  String get damage => _damage.text;

  /// Теги-стихии. По ним же названы типы урона — см. [DamageType.tag].
  static const elements = [fire, cold, lightning, voidTag, physical];

  /// Формы. Ровно одна на способность, и валидатор это проверяет.
  static const forms = [attack, spell];
}

/// Тип урона. Отделён от [Tag] намеренно: тег — это принадлежность билду,
/// тип урона — это то, что режется сопротивлением цели. Способность с тегом
/// [Tag.blood] может наносить физический урон.
enum DamageType {
  physical(Phrase('Физический', 'Physical'), Tag.physical),
  fire(Phrase('Огонь', 'Fire'), Tag.fire),
  cold(Phrase('Холод', 'Cold'), Tag.cold),
  lightning(Phrase('Молния', 'Lightning'), Tag.lightning),
  voidType(Phrase('Пустота', 'Void'), Tag.voidTag);

  const DamageType(this._title, this.tag);

  final Phrase _title;

  String get title => _title.text;

  /// Тег-стихия, который обязан стоять у способности этого типа урона.
  ///
  /// Связь объявлена здесь, чтобы валидатор мог её проверить: огненная
  /// способность без тега «Огонь» не попадала бы ни в один огненный билд, и
  /// заметить это можно было бы только замером.
  final Tag tag;
}

/// Источник события, у которого есть теги, — способность.
///
/// Отдельный интерфейс, потому что шина намеренно слабо типизирована:
/// `EventContext.source` объявлен как `Object?`, чтобы `core/sim` не знал о
/// боевых сущностях. Триггеру же нужны именно теги, и только они.
abstract class TaggedSource {
  List<Tag> get tags;
}
