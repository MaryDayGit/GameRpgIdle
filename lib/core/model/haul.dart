import '../balance/curves.dart';
import '../sim/crafting.dart';
import 'gear.dart';
import 'item.dart';
import 'shard.dart';

/// Добыча наёмника за один спуск.
///
/// Ключевое правило нового цикла: игрок НЕ получает лут по ходу спуска.
/// Всё, что наёмник нашёл, лежит у него в рюкзаке и попадает игроку только
/// когда контракт закрыт — гибелью или отзывом. Отсюда два следствия:
///
///  * возврат в игру становится обязательным действием, а не привычкой;
///  * вместимость рюкзака — диегетическое объяснение «правила витрины»
///    (GDD §4.5): не игра прячет лут, а у наёмника кончается место.
///
/// Снаряжение наёмника при этом НЕ меняется: что игрок надел, с тем боец и
/// идёт до конца. Всё найденное — только груз, и место в рюкзаке делят между
/// собой одни находки.
class Haul {
  Haul({required this.capacity, required this.salvageRate});

  /// Вместимость рюкзака наёмника.
  ///
  /// Больше НЕ ограничивает: наёмник несёт наверх всё найденное. Осталась
  /// числом ранга — его показывает карточка наёмника, и оно по-прежнему
  /// что-то говорит об опытности, — но добычу не режет.
  final int capacity;

  /// Доля стоимости, возвращаемая золотом за не влезшее (уровень Алтаря).
  final double salvageRate;

  /// Донесённые находки, отсортированы по убыванию уровня.
  ///
  /// Снаряжение наёмника сюда не попадает никогда: он его не снимает.
  final List<Item> items = [];

  double gold = 0.0;

  /// Осколки, снятые с распылённого.
  ///
  /// Рюкзак ограничен, и всё сверх него уходит в распыл. Раньше от этого
  /// оставалось только золото, и «+50 % количества добычи» на модификаторе
  /// этажа не значило почти ничего: рюкзак и так полон, а золото сильнее
  /// растёт от глубины. Осколок — то, ради чего количество вообще нужно.
  final List<Shard> shards = [];

  /// Сколько осколков не влезло в Верстак при получении добычи.
  int shardsLost = 0;
  int relics = 0;
  int lockpicks = 0;

  /// Сколько предметов распылено из-за нехватки места.
  int salvagedCount = 0;

  /// Золото, полученное распылением излишков.
  double salvagedGold = 0.0;

  bool collected = false;

  /// Кладёт находку в рюкзак. Рюкзак бесконечен: наёмник несёт наверх всё.
  ///
  /// Раньше сверх вместимости он распылял сам, по правилу «худшее за борт».
  /// Правило разумное, но оно принимало за игрока главное решение цикла:
  /// что оставить. «Худшая по уровню» вещь вполне может быть единственной с
  /// нужным тегом — а наёмник про сборку не знает ничего.
  ///
  /// Теперь ограничен сундук, а не рюкзак, и разбирает добычу игрок.
  void addItem(Item item) {
    items.add(item);
    items.sort((a, b) => b.ilvl.compareTo(a.ilvl));
  }

  /// Переплавка вещи: золото и, если было что снять, осколок.
  ///
  /// Раньше вызывалась только рюкзаком при переполнении. Теперь её зовёт
  /// игрок из разбора добычи — правило то же, решение другое.
  Shard? salvage(Item item) {
    salvagedCount++;
    final value = Curves.goldBase * Curves.itemScale(item.ilvl);
    salvagedGold += value * salvageRate;
    gold += value * salvageRate;

    // Редкое не исчезает бесследно: с него снимается лучший аффикс.
    // Правило детерминированное, без броска: разбор идёт уже после того, как
    // спуск посчитан, и лишний бросок сдвинул бы всю случайность.
    if (item.rarity.rank < Rarity.rare.rank || item.affixes.isEmpty) {
      return null;
    }

    var best = 0;
    for (var i = 1; i < item.affixes.length; i++) {
      if (item.affixes[i].percentile > item.affixes[best].percentile) best = i;
    }
    final shard = Crafting.extract(item, best);
    shards.add(shard);
    return shard;
  }

  int get itemCount => items.length;

  double get totalGold => gold;

  /// Лучшее, что принёс наёмник, — то, что игрок увидит первым в отчёте.
  int get bestIlvl => items.isEmpty ? 0 : items.first.ilvl;

  @override
  String toString() => 'Haul(находок ${items.length}/$capacity, '
      'золото ${gold.toStringAsFixed(0)}, осколков ${shards.length}, '
      'распылено $salvagedCount)';
}
