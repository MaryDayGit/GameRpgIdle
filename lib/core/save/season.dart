/// Сезон: раздел, в котором живёт прогресс игрока.
///
/// Сезон — не косметика и не список наград. Это ОТВЕТ НА ВОПРОС «к какому
/// прогону относится этот сейв», и он нужен формату с первого дня по той же
/// причине, по которой с первого дня заведена цепочка миграций
/// (`migrations.dart`): сейв без сезона нельзя разделить задним числом. Когда
/// выйдет первое крупное обновление и понадобится начать с чистого листа,
/// у уже существующих сейвов не будет поля, по которому их отличить от
/// новых, — и «обнулить всем прогресс» превратится в «стереть всем прогресс».
///
/// ## Что означает смена сезона
///
/// **Не удаление.** Сейв прошлого сезона остаётся: локально — отдельным
/// файлом с именем сезона, в облаке — отдельным документом
/// (`players/{uid}/saves/{seasonId}`). Игрок начинает с чистого листа, но
/// доказанное им в нулевом сезоне никуда не девается. Это разница между
/// «сезон кончился» и «нас обокрали», и она стоит одного лишнего документа
/// в Firestore.
///
/// **Разделение, а не флаг.** Сезон — часть АДРЕСА сейва, а не поле внутри
/// него. Поле пришлось бы проверять в каждом месте, которое читает профиль;
/// адрес проверяется один раз, при загрузке, и дальше в игре нет ни одного
/// места, которое знало бы про сезоны вообще.
///
/// ## Почему [current] пока константа
///
/// Сезон обязан приезжать снаружи — из Remote Config или из документа
/// Firestore, — иначе дата обнуления зашита в APK, и сдвинуть её можно
/// только новой сборкой в Google Play с её сутками проверки. Пока сезон один,
/// значение живёт здесь; когда сезонов станет два, меняется одна эта строка
/// и источник, а формат сейва, раскладка в облаке и разрешение конфликтов
/// остаются те же. Ради этого поле и заводится сейчас, а не потом.
class Season {
  const Season(this.id);

  /// Идентификатор. Он же — имя документа в Firestore и суффикс архивного
  /// файла, поэтому только буквы, цифры и подчёркивание.
  final String id;

  /// Нулевой сезон: то, с чем игра выходит.
  ///
  /// Ноль, а не единица, намеренно. Первый сезон — это первое ОБНОВЛЕНИЕ с
  /// обнулением, а не релиз; называть релиз первым сезоном значит на всю
  /// жизнь игры сдвинуть нумерацию на единицу относительно того, как её
  /// считают игроки.
  static const Season zero = Season('season_0');

  /// Сезон, в который играют сейчас.
  static const Season current = zero;

  /// Сейв этого сезона или чужого. Чужой не загружается в текущую игру:
  /// его модели могут не совпасть с нынешним контентом вовсе, а
  /// снисходительная загрузка (`codec.dart`) починила бы это молча — то есть
  /// показала бы игроку изувеченный прошлый сезон вместо чистого нового.
  static bool isCurrent(String? seasonId) => seasonId == current.id;

  @override
  String toString() => id;
}
