import '../content/content_pack.dart';
import '../content/floor_modifier_def.dart';
import 'rng.dart';

/// Разлом дня: один спуск в сутки по общему для всех расписанию.
///
/// Существует ради единственного вопроса, на который у игры не было ответа:
/// **чем завтра отличается от сегодня.** Всё остальное в ней — накопление, и
/// накопление одинаково в любой день. Разлом даёт день с собственным лицом:
/// свой сид, свой модификатор на КАЖДОМ этаже и своя награда.
///
/// Сутки считаются по UTC. Не по местному времени намеренно: игрок, летящий
/// через часовые пояса, иначе получал бы два разлома в день или ни одного, а
/// «сегодня» — это то, что одинаково для всех.
class DailyRift {
  const DailyRift({
    required this.day,
    required this.seed,
    required this.modifier,
  });

  /// Номер суток от эпохи. Он же — ключ «сегодня» в сохранении.
  final int day;

  /// Сид спуска. Выводится из дня, поэтому один и тот же весь день: разлом
  /// нельзя перекатить, закрыв приложение.
  final int seed;

  /// Модификатор, действующий на КАЖДОМ этаже, а не между развилками.
  ///
  /// В этом и состоит лицо дня: обычный спуск чередует модификаторы, разлом
  /// живёт под одним от начала до конца.
  final FloorModifierDef modifier;

  /// Номер суток для момента [at].
  static int dayOf(DateTime at) =>
      at.toUtc().difference(DateTime.utc(1970)).inDays;

  /// Разлом на сутки [at]. Детерминирован: два вызова в один день дают один
  /// разлом, и пересчитать его дешевле, чем хранить.
  static DailyRift on(DateTime at) {
    final day = dayOf(at);
    final all = ContentPack.current.floorModifiers;
    if (all.isEmpty) {
      throw StateError('Нет модификаторов этажей');
    }

    // Сид разлома отделён от сида дня: иначе номер модификатора и сам спуск
    // катились бы из одного числа, и «Жар» всегда выпадал бы вместе с одной
    // и той же расселиной.
    final rng = Rng.stream(day, 0, 0, RngPurpose.floorModifier);

    return DailyRift(
      day: day,
      seed: Rng.stream(day, 1, 0, RngPurpose.fork).nextInt(1 << 30),
      modifier: all[rng.nextInt(all.length)],
    );
  }
}
