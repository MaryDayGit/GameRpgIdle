/// Что произошло в бою — для показа, а не для механики.
///
/// Отдельно от [EventBus] намеренно. Шина событий — часть симуляции: у неё
/// бюджет срабатываний на тик и предохранитель от каскадов, и подписчик на
/// ней РАСХОДУЕТ этот бюджет. Подписав экран, мы получили бы бой, который
/// идёт иначе, когда на него смотрят: лишний слушатель выбирает бюджет, и
/// чей-то триггер не срабатывает. Повтор разошёлся бы с записанным раном —
/// то есть игрок увидел бы бой, которого не было.
///
/// Поэтому здесь односторонний канал: симуляция пишет, наблюдатель забирает,
/// и никто в симуляции его не читает. Выключенный канал (`null`) не стоит
/// ничего — офлайн-расчёт на миллионы тиков не должен платить за анимацию,
/// которую никто не смотрит.
library;

import '../model/grammar.dart';

enum BeatKind {
  /// Началась новая волна. В `amount` — сколько в ней мобов.
  ///
  /// Нужен не для красоты: индексы в остальных записях относятся к ТЕКУЩЕЙ
  /// волне, и записи, не забранные до её конца, указывали бы на фигуры уже
  /// другой пачки. Наблюдатель сбрасывает по этой записи всё накопленное.
  waveStarted,

  /// Герой замахнулся автоатакой.
  heroSwing,

  /// Герой применил способность.
  heroCast,

  /// По мобу попали.
  enemyHit,

  /// Моб умер.
  enemyDied,

  /// Попали по герою.
  heroHurt,

  /// Герой погиб.
  heroDied,
}

/// Одно событие для анимации: что, по кому и насколько сильно.
class CombatBeat {
  const CombatBeat(
    this.kind, {
    this.index = -1,
    this.amount = 0.0,
    this.crit = false,
    this.id = '',
    this.name = '',
    this.gender = Gender.masculine,
  });

  final BeatKind kind;

  /// Индекс моба в волне. `-1` — событие про героя.
  final int index;

  final double amount;
  final bool crit;

  /// `id` способности для [BeatKind.heroCast], иначе пусто.
  final String id;

  /// Имя того, с кем это случилось: моба — для [BeatKind.enemyDied].
  ///
  /// Запись обязана быть самодостаточной. Наблюдатель забирает её на кадр
  /// позже, а к тому моменту волны может уже не быть — и строка «„“ пал»
  /// с пустым именем это ровно то, что видел живой прогон.
  final String name;

  /// Род имени: «повержен» или «повержена». Без него запись пришлось бы
  /// согласовывать по бестиарию уже на экране — то есть искать моба, которого
  /// в волне может уже не быть.
  final Gender gender;

  @override
  String toString() => 'CombatBeat(${kind.name}, $index)';
}

/// Накопитель событий боя.
///
/// Ёмкость ограничена, и переполнение теряет СТАРЫЕ записи: наблюдатель
/// догоняет спуск тысячами тиков за кадр, и показывать надо последнее, что
/// случилось, а не первое. Неограниченный список в этом режиме — утечка,
/// растущая ровно так же быстро, как идёт перемотка.
class CombatFeed {
  CombatFeed({this.capacity = 64});

  final int capacity;
  final List<CombatBeat> _beats = [];

  int get length => _beats.length;
  bool get isEmpty => _beats.isEmpty;

  void add(CombatBeat beat) {
    _beats.add(beat);
    if (_beats.length > capacity) _beats.removeRange(0, _beats.length - capacity);
  }

  /// Забирает накопленное. Именно забирает: анимация проигрывается один раз,
  /// а повторная выдача тех же событий — это удар, который бьёт дважды.
  List<CombatBeat> drain() {
    if (_beats.isEmpty) return const [];
    final out = List<CombatBeat>.of(_beats);
    _beats.clear();
    return out;
  }

  void clear() => _beats.clear();
}
